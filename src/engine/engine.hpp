  nlohmann::json observation(Player viewer) const;

  Decision decide(Player p, Request req);

  // ---- decision validation -------------------------------------------------
  // Agents are untrusted: every decision is validated before use. Illegal
  // indices are dropped, disabled or duplicate picks are refused, and the
  // selection is repaired to [minSel, maxSel]. Violations are counted per
  // player; past cfg.illegalTolerance the offender forfeits the match.
  int illegal_count(Player p) const { return illegalCount_[p]; }
  int lua_error_count() const;  // card-effect runtime errors during the match
  bool forfeited() const { return forfeited_; }

  // ---- match flow ----------------------------------------------------------
  void setup_match();
  void run();

  // ---- replay / determinism ------------------------------------------------
  // The engine records every decision it receives. Replaying the same seed and
  // journal reproduces the match exactly; state_hash() lets us verify it.
  void start_recording();
