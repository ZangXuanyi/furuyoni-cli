  std::string ruleset_summary() const;

  void set_agent(Player p, Agent* a);

  // ---- accessors -----------------------------------------------------------
  PlayerState& ps(Player p) { return st.p[p]; }
  const PlayerState& ps(Player p) const { return st.p[p]; }
