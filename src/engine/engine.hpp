  void remove_all_normals(Player p);                  // 残响装置: 移除所有非切牌
  void skip_next_main(Player p) { ps(p).skipMainPhase = true; }
  void add_temp_distance(Player p, int n) { ps(p).tempDistanceMod += n; }
